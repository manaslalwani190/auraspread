# Build the frozen set once at import time
MCX_HOLIDAYS: FrozenSet[date] = frozenset(
    date.fromisoformat(d) for d in _HOLIDAY_STRINGS
)


def is_mcx_holiday(d: date) -> bool:
    """
    Return True if `d` is a known MCX trading holiday (weekday closure).

    Note: weekends (Sat/Sun) are *always* non-trading; call this for
    weekdays only, or use `is_mcx_trading_day` for a combined check.
    """
    return d in MCX_HOLIDAYS


def is_mcx_trading_day(d: date) -> bool:
    """
    Return True if `d` is a regular MCX trading day:
      - Not a Saturday or Sunday
      - Not a known MCX holiday
    """
    if d.weekday() >= 5:  # 5 = Saturday, 6 = Sunday
        return False
    return d not in MCX_HOLIDAYS


